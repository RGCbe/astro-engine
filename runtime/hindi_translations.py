def hindi(en_term, default=None):
    """Look up Hindi translation; fall back to English or default."""
    for d in [PLANETS_HI, RASIS_HI, NAKSHATRAS_HI, WEEKDAYS_HI,
               TITHIS_HI, KARANAS_HI, YOGAS_PANCH_HI, LABELS_HI, SECTION_HEADERS_HI]:
        if en_term in d:
            v = d[en_term]
            return v if isinstance(v, str) else v[0]
    return default if default is not None else en_term


